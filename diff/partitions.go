// diffPartitions compares the partition clauses of `current` and
// `desired` (both already normalised through
// `parser.NormalizePartitionOption`, both stored on
// `model.Table.Partition` as `*string`). Returns the executable
// `ALTER TABLE … ADD/DROP PARTITION` statements, the suppressed
// drops (when `--allow-drop=partition` is unset), and an error
// for any partition diff myschema doesn't generate yet.
//
// v1 scope (this PR):
//
//   - both sides nil → no-op.
//   - both sides set, byte-equal → no-op.
//   - one side nil → error (adding / removing partitioning to/from
//     an existing table is REMOVE PARTITIONING + new PARTITION BY,
//     a future PR).
//   - partition strategy (RANGE/LIST/HASH/KEY/...COLUMNS),
//     expression, or column list differs → error (scheme change
//     is a future PR).
//   - HASH/KEY → error (count operations need their own grammar:
//     COALESCE PARTITION / ADD PARTITION PARTITIONS n; future PR).
//   - RANGE/LIST: definitions go through an order-preserving
//     subset diff. Pure suffix add (current's list is a prefix
//     of desired's) → ADD PARTITION. Order-preserving subset
//     drop (desired matches a same-order subsequence of
//     current) → DROP PARTITION — head, middle, and tail
//     removals are all generated, since `ALTER TABLE … DROP
//     PARTITION p1, p2` accepts a discontinuous name list.
//     Anything else (a value change, an interior insert, or a
//     reorder — i.e. the diff yields both an ADD list AND a
//     DROP list) → error so the user falls back to manual
//     REORGANIZE.
//
// CAVEATS.md "Partitioning" documents the user-facing rules.
func diffPartitions(fqtn string, current, desired *string, dc DropChecker) ([]string, []string, error) {
	if current == nil && desired == nil {
		return nil, nil, nil
	}
	if current != nil && desired != nil && *current == *desired {
		return nil, nil, nil
	}
	if current == nil {
		// desired adds partitioning to an unpartitioned catalog table.
		// First-time `ALTER TABLE … PARTITION BY …` generation is a
		// future PR — point the user at the right ALTER for *this*
		// direction so the manual fallback isn't backwards.
		return nil, nil, fmt.Errorf("table %s: desired SQL partitions a table that the catalog has unpartitioned; first-time ALTER TABLE … PARTITION BY … is not yet generated by myschema. Run the PARTITION BY by hand and let the next plan reconverge", fqtn)
	}
	if desired == nil {
		// desired drops partitioning from a partitioned catalog
		// table — the inverse of the case above.
		return nil, nil, fmt.Errorf("table %s: desired SQL drops the partitioning the catalog still has; ALTER TABLE … REMOVE PARTITIONING is not yet generated by myschema. Run the REMOVE PARTITIONING by hand and let the next plan reconverge", fqtn)
	}

	curPO, err := parser.ParsePartitionClause(*current)
	if err != nil {
		return nil, nil, fmt.Errorf("table %s: re-parse current partition clause: %w", fqtn, err)
	}
	desPO, err := parser.ParsePartitionClause(*desired)
	if err != nil {
		return nil, nil, fmt.Errorf("table %s: re-parse desired partition clause: %w", fqtn, err)
	}
	// Strategy / expression / column list mismatch → scheme change,
	// out of scope for v1.
	if !partitionHeaderEqual(curPO, desPO) {
		return nil, nil, fmt.Errorf("table %s: partition strategy / expression differs between catalog and desired SQL; partition scheme changes are not yet generated by myschema. Run two separate ALTERs by hand — `ALTER TABLE … REMOVE PARTITIONING` followed by `ALTER TABLE … PARTITION BY …` — and let the next plan reconverge", fqtn)
	}
	// HASH/KEY use count-based grammar (COALESCE PARTITION /
	// ADD PARTITION PARTITIONS n) — different code path, future PR.
	// Before erroring, check whether this is actually a no-op:
	// `partitionHeaderEqual` lower-cases ColList for KEY (and the
	// expression for HASH), so two semantically-equal clauses that
	// differ only in identifier casing reach this branch even though
	// nothing has actually changed. The raw-string fast path at the
	// top would have caught the byte-equal case but not the
	// case-only diff. Equal `Partitions` count plus equal headers
	// means there's nothing to do.
	if curPO.Type != sqlparser.RangeType && curPO.Type != sqlparser.ListType {
		if curPO.Partitions == desPO.Partitions {
			return nil, nil, nil
		}
		return nil, nil, fmt.Errorf("table %s: HASH / KEY partition diffs are not yet generated by myschema (RANGE / LIST only in this version). Run ALTER TABLE … COALESCE PARTITION / ADD PARTITION PARTITIONS by hand", fqtn)
	}

	curDefs := curPO.Definitions
	desDefs := desPO.Definitions

	// Order-preserving subset diff. Each current partition is either
	// kept (matched by the next-unconsumed desired partition) or
	// dropped; anything left in desired after the walk is a suffix
	// add. The three observable outcomes:
	//   - both empty → no-op (catches the equality cases the raw-
	//     string fast path missed because of formatting drift).
	//   - pure ADD (drops empty, adds non-empty) → suffix grow.
	//   - pure DROP (adds empty, drops non-empty) → any subset
	//     dropped while preserving the remaining order; head /
	//     tail / interior drops all generated as
	//     `DROP PARTITION p1, p2, …`.
	//   - drops AND adds both non-empty → REORGANIZE territory.
	//     A previous attempt to emit DROP + ADD whenever the name
	//     sets were disjoint was unsafe: a "merge" shape like
	//     `[p0<10,p1<20,p2<30] -> [p0<10,q1<40]` has disjoint
	//     names yet semantically expects q1 to inherit the rows
	//     from p1 and p2. Plain DROP + ADD would silently lose
	//     that data. Disjoint-name detection isn't enough on its
	//     own to tell merge / split / replace shapes apart from a
	//     pure retention roll-forward, so we conservatively error
	//     and let the user run REORGANIZE PARTITION (or the
	//     individual DROP / ADD pair, when they really do want to
	//     discard the partitioned data) by hand.
	drops, adds := partitionByNameOrderPreserving(curDefs, desDefs)
	if len(drops) > 0 && len(adds) > 0 {
		return nil, nil, fmt.Errorf("table %s: partition definitions differ in a way that needs both ADD and DROP (a value change, an interior insert, a reorder, or a merge / split using new partition names); REORGANIZE PARTITION generation is not yet implemented, and a plain DROP + ADD pair would silently lose any rows that should have moved into the new partition. Run the ALTER by hand and let the next plan reconverge", fqtn)
	}

	var stmts, disallowed []string

	if len(adds) > 0 {
		var b strings.Builder
		b.WriteString("ALTER TABLE ")
		b.WriteString(fqtn)
		b.WriteString(" ADD PARTITION (")
		for i, d := range adds {
			if i > 0 {
				b.WriteString(",\n  ")
			} else {
				b.WriteString("\n  ")
			}
			b.WriteString(parser.FormatPartitionDefinition(d))
		}
		b.WriteString("\n);")
		stmts = append(stmts, b.String())
	}

	if len(drops) > 0 {
		names := make([]string, 0, len(drops))
		for _, d := range drops {
			// Quote through model.Ident so a partition named with a
			// MySQL reserved word or non-safe identifier round-trips
			// correctly. ADD PARTITION already inherits quoting via
			// vitess's PartitionDefinition formatter; DROP PARTITION
			// needs to do it explicitly because we only emit the bare
			// name list.
			names = append(names, model.Ident(d.Name.String()))
		}
		drop := "ALTER TABLE " + fqtn + " DROP PARTITION " + strings.Join(names, ", ") + ";"
		if dc.IsDropAllowed("partition") {
			stmts = append(stmts, drop)
		} else {
			disallowed = append(disallowed, "-- skipped: "+drop)
		}
	}

	return stmts, disallowed, nil
}

// partitionHeaderEqual checks that two PartitionOptions describe the
// same strategy: same Type (RANGE / LIST / HASH / KEY), same column
// list (KEY / RANGE COLUMNS / LIST COLUMNS), same expression (RANGE
// / LIST / HASH), same IsLinear / KeyAlgorithm flags. Definitions
// themselves are compared separately.
func partitionHeaderEqual(a, b *sqlparser.PartitionOption) bool {
	if a == nil || b == nil {
		return a == b
	}
	if a.Type != b.Type || a.IsLinear != b.IsLinear || a.KeyAlgorithm != b.KeyAlgorithm {
		return false
	}
	if !stringSliceEqual(colListNames(a.ColList), colListNames(b.ColList)) {
		return false
	}
	// Compare expressions through vitess's formatter directly. Both
	// AST trees were built by re-parsing the strings already
	// produced by parser.NormalizePartitionOption, which lower-cased
	// function / column identifiers in place — so the formatted
	// outputs already match on identifier casing without us having
	// to re-run anything here. Critically, we must NOT lower-case
	// the formatted string ourselves: that would also collapse
	// string-literal case (`'US'` vs `'us'`) and silently equate
	// real expression changes like `WHEN region='US'` ↔
	// `WHEN region='us'`.
	return formatExpr(a.Expr) == formatExpr(b.Expr)
}

func colListNames(cols sqlparser.Columns) []string {
	out := make([]string, 0, len(cols))
	for _, c := range cols {
		out = append(out, strings.ToLower(c.String()))
	}
	return out
}

func formatExpr(e sqlparser.Expr) string {
	if e == nil {
		return ""
	}
	return sqlparser.String(e)
}

func stringSliceEqual(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

// partitionByNameOrderPreserving walks `cur` once, matching each
// definition against the next-unconsumed entry of `des`. Matched
// pairs are kept; unmatched current entries are added to `drops`;
// any leftover desired entries become `adds`. Order is preserved
// on both sides — the caller treats a "drops + adds both
// non-empty" outcome as an interior reshape (REORGANIZE).
//
// `partitionDefEqual` already accounts for the
// NormalizePartitionOption / ParsePartitionClause round-trip
// (engine strip, identifier lower-casing, etc.) so name+value
// equality here is bytewise on the canonical form.
func partitionByNameOrderPreserving(cur, des []*sqlparser.PartitionDefinition) (drops, adds []*sqlparser.PartitionDefinition) {
	di := 0
	for _, c := range cur {
		if di < len(des) && partitionDefEqual(c, des[di]) {
			di++
			continue
		}
		drops = append(drops, c)
	}
	if di < len(des) {
		adds = append(adds, des[di:]...)
	}
	return drops, adds
}

func partitionDefEqual(a, b *sqlparser.PartitionDefinition) bool {
	if a == nil || b == nil {
		return a == b
	}
	if a.Name.String() != b.Name.String() {
		return false
	}
	return parser.FormatPartitionDefinition(a) == parser.FormatPartitionDefinition(b)
}
